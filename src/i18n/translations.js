const exactLower = new Map(
  Object.entries(EXACT_KM).map(([key, value]) => [
    key.toLowerCase(),
    value
  ])
);

const sortedTerms = Object.entries(TERM_KM)
  .sort((left, right) => right[0].length - left[0].length);

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function interpolate(value, variables = {}) {
  return String(value).replace(
    /\{\{\s*([\w.]+)\s*\}\}/g,
    (_, key) => variables[key] ?? ""
  );
}

function preserveOuterWhitespace(source, translated) {
  const leading = source.match(/^\s*/)?.[0] || "";
  const trailing = source.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}

function likelyBusinessData(value) {
  const trimmed = value.trim();

  if (!trimmed || !/[A-Za-z]/.test(trimmed)) return true;
  if (/^(https?:\/\/|mailto:|tel:)/i.test(trimmed)) return true;
  if (/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(trimmed)) return true;
  if (/^[A-Z0-9_-]{2,20}$/.test(trimmed) && !EXACT_KM[trimmed]) {
    return true;
  }
  if (/^[A-Z]{3}-[A-Z0-9-]+$/.test(trimmed)) return true;
  if (/^\$?\d[\d,.]*(?:\s?(?:USD|KHR|%|pcs?|box|pack))?$/i.test(trimmed)) {
    return true;
  }

  return false;
}

function dynamicTranslation(value) {
  const loading = value.match(/^Loading\s+(.+?)(?:\.{3}|…)?$/i);
  if (loading) {
    return `កំពុងផ្ទុក${translateUiText(loading[1], "km")}...`;
  }

  const noFound = value.match(/^No\s+(.+?)\s+found\.?$/i);
  if (noFound) {
    return `រកមិនឃើញ${translateUiText(noFound[1], "km")}។`;
  }

  const saved = value.match(/^(.+?)\s+saved\.?$/i);
  if (saved) {
    return `បានរក្សាទុក${translateUiText(saved[1], "km")}។`;
  }

  const created = value.match(/^(.+?)\s+created\.?$/i);
  if (created) {
    return `បានបង្កើត${translateUiText(created[1], "km")}។`;
  }

  const updated = value.match(/^(.+?)\s+updated\.?$/i);
  if (updated) {
    return `បានកែប្រែ${translateUiText(updated[1], "km")}។`;
  }

  const count = value.match(/^(\d[\d,.]*)\s+(.+)$/);
  if (count) {
    return `${count[1]} ${translateUiText(count[2], "km")}`;
  }

  return null;
}

export function normalizeLanguage(value) {
  return String(value || "").toLowerCase().startsWith("km")
    ? "km"
    : "en";
}

export function languageLabel(value) {
  return normalizeLanguage(value) === "km"
    ? "ខ្មែរ"
    : "English";
}

export function translateUiText(
  value,
  language = "en",
  variables = {}
) {
  const source = interpolate(value ?? "", variables);
  const normalizedLanguage = normalizeLanguage(language);

  if (normalizedLanguage === "en") return source;

  const trimmed = source.trim();
  if (!trimmed) return source;

  const exact = EXACT_KM[trimmed]
    || exactLower.get(trimmed.toLowerCase());

  if (exact) {
    return preserveOuterWhitespace(source, exact);
  }

  if (likelyBusinessData(trimmed)) return source;

  const dynamic = dynamicTranslation(trimmed);
  if (dynamic) {
    return preserveOuterWhitespace(source, dynamic);
  }

  let translated = trimmed;

  for (const [english, khmer] of sortedTerms) {
    const expression = new RegExp(
      `(^|[^A-Za-z])(${escapeRegExp(english)})(?=$|[^A-Za-z])`,
      "gi"
    );

    translated = translated.replace(
      expression,
      (_, prefix) => `${prefix}${khmer}`
    );
  }

  return preserveOuterWhitespace(source, translated);
}

export function createTranslator(language) {
  return (value, variables) =>
    translateUiText(value, language, variables);
}
